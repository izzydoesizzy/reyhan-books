/* ============================================================
   Reyhan's Story Shelf — book details fetcher
   ------------------------------------------------------------
   Enriches the thin catalogs (EARLY_BOOKS in data.js and every
   book in library-data.js) with real metadata from Open Library:
   synopsis (works API), page count, ISBNs, publisher, year.
   (Google Books was the original primary source, but its free
   per-IP daily quota is tiny — Open Library allows ~1 req/sec.)

   Output: book-details.js — `const BOOK_DETAILS = { <id>: {...} }`,
   loaded by index.html and overlaid onto books at render time.
   Never edits data.js or library-data.js.

   Re-runnable: ids already present in book-details.js are skipped,
   so an interrupted run resumes where it left off. Delete an id
   (or the whole file) to force a re-fetch.

   Also writes book-details-audit.json: for early books the stored
   ISBN is looked up and the returned title/author compared against
   ours — mismatches mean the entry may describe the wrong book or
   edition (how the Treasury of Fairy Tales mix-up happened).

   Usage: node fetch-book-details.mjs
   ============================================================ */

import fs from "node:fs";
import vm from "node:vm";

const OUT_FILE = "book-details.js";
const AUDIT_FILE = "book-details-audit.json";
const DELAY_MS = 600;
const UA = { "User-Agent": "reyhan-books-enricher/1.0 (personal family reading log)" };

/* ---------- load catalogs ---------- */

const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync("data.js", "utf8") + ";this.EARLY=EARLY_BOOKS;", ctx);
vm.runInContext(fs.readFileSync("library-data.js", "utf8") + ";this.LIB=LIBRARY_SERIES;", ctx);

const earlyBooks = ctx.EARLY;
const libraryBooks = ctx.LIB.flatMap((s) =>
  s.books.map((b) => ({ ...b, seriesName: s.name }))
);

/* ---------- resume ---------- */

let details = {};
if (fs.existsSync(OUT_FILE)) {
  const m = fs.readFileSync(OUT_FILE, "utf8").match(/const BOOK_DETAILS = (\{[\s\S]*\});/);
  if (m) details = JSON.parse(m[1]);
  console.log(`resuming: ${Object.keys(details).length} ids already done`);
}
const audit = fs.existsSync(AUDIT_FILE) ? JSON.parse(fs.readFileSync(AUDIT_FILE, "utf8")) : [];
const audited = new Set(audit.map((a) => a.id));

/* ---------- helpers ---------- */

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const norm = (s) =>
  String(s || "").toLowerCase().replace(/[^a-z0-9 ]+/g, " ").replace(/\s+/g, " ").trim();

function save() {
  const header =
    "/* Generated by fetch-book-details.mjs — do not edit by hand.\n" +
    "   Extra metadata for early books + discover-library books,\n" +
    "   overlaid onto book objects at render time by app.js. */\n";
  fs.writeFileSync(OUT_FILE, header + "const BOOK_DETAILS = " + JSON.stringify(details, null, 2) + ";\n");
  fs.writeFileSync(AUDIT_FILE, JSON.stringify(audit, null, 2) + "\n");
}

async function ol(path) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch("https://openlibrary.org" + path, { headers: UA });
      if (res.status === 429 || res.status === 503) {
        await sleep(4000 * (attempt + 1));
        continue;
      }
      if (!res.ok) return null;
      return await res.json();
    } catch {
      await sleep(2000);
    }
  }
  return null;
}

const SEARCH_FIELDS = "key,title,author_name,number_of_pages_median,first_publish_year,publisher,isbn";
async function olSearch(q) {
  const json = await ol("/search.json?limit=5&fields=" + SEARCH_FIELDS + "&q=" + encodeURIComponent(q));
  await sleep(DELAY_MS);
  return (json && json.docs) || [];
}

function titlesAgree(a, b) {
  const na = norm(a), nb = norm(b);
  return !!na && !!nb && (na.includes(nb) || nb.includes(na));
}

/* Loose author agreement: any surname from ours appears in theirs. */
function authorsAgree(ours, theirs) {
  if (!ours || !theirs) return true; /* nothing to compare */
  const theirNorm = norm(Array.isArray(theirs) ? theirs.join(" ") : theirs);
  return norm(ours)
    .split(" ")
    .filter((w) => w.length > 2)
    .some((w) => theirNorm.includes(w));
}

function pickDoc(docs, title) {
  return docs.find((x) => titlesAgree(x.title, title)) || null;
}

function trimSynopsis(text) {
  let t = String(text).replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
  /* OL descriptions often end with cataloguer notes after a "----" or
     source line; keep just the blurb. */
  t = t.split(/-{3,}|\[source\]|\(source\)/i)[0].trim();
  if (t.length <= 500) return t;
  const cut = t.slice(0, 500);
  const end = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf("! "), cut.lastIndexOf("? "));
  return end > 150 ? cut.slice(0, end + 1) : cut + "…";
}

async function workDescription(workKey) {
  if (!workKey) return null;
  const w = await ol(workKey + ".json");
  await sleep(DELAY_MS);
  if (!w || !w.description) return null;
  const raw = typeof w.description === "string" ? w.description : w.description.value;
  return raw ? trimSynopsis(raw) : null;
}

function detailsFromDoc(doc) {
  const d = {};
  if (doc.number_of_pages_median > 0) d.pages = doc.number_of_pages_median;
  const isbns = doc.isbn || [];
  const isbn13 = isbns.find((i) => /^97[89]\d{10}$/.test(i));
  const isbn10 = isbns.find((i) => /^\d{9}[\dXx]$/.test(i));
  if (isbn13) d.isbn13 = isbn13;
  if (isbn10) d.isbn10 = isbn10;
  if (doc.publisher && doc.publisher.length) d.publisher = doc.publisher[0];
  if (doc.first_publish_year) d.published = String(doc.first_publish_year);
  return d;
}

/* ---------- main ---------- */

const queue = [];
for (const b of earlyBooks) {
  queue.push({ id: b.id, title: b.title, author: b.author, isbn: b.coverIsbn, kind: "early" });
}
for (const b of libraryBooks) {
  queue.push({ id: b.id, title: b.title, author: b.author, series: b.seriesName, kind: "library" });
}

console.log(`${queue.length} books to process (${earlyBooks.length} early, ${libraryBooks.length} library)`);

let done = 0;
for (const item of queue) {
  const needFetch = !details[item.id];
  const needAudit = item.kind === "early" && !audited.has(item.id);
  if (!needFetch && !needAudit) continue;

  try {
    let doc = null;

    /* Early books: precise ISBN lookup, which doubles as the audit. */
    if (item.isbn) {
      const docs = await olSearch("isbn:" + item.isbn);
      doc = docs[0] || null;
      if (needAudit) {
        if (!doc) {
          audit.push({ id: item.id, title: item.title, isbn: item.isbn, problem: "ISBN not found in Open Library" });
        } else {
          const tOk = titlesAgree(doc.title, item.title);
          const aOk = authorsAgree(item.author, doc.author_name);
          if (!tOk || !aOk) {
            audit.push({
              id: item.id, title: item.title, author: item.author, isbn: item.isbn,
              problem: !tOk ? "title mismatch" : "author mismatch",
              isbnResolvesTo: { title: doc.title, authors: (doc.author_name || []).join(" / ") },
            });
          }
        }
        audited.add(item.id);
      }
      /* A doc found by ISBN but with a clashing title is the wrong
         record to enrich from - drop it and fall through to search. */
      if (doc && !titlesAgree(doc.title, item.title)) doc = null;
    }

    if (!doc && needFetch) {
      const author = String(item.author || "").split("/")[0].replace(/\(.*?\)/g, "").trim();
      let docs = await olSearch('title:"' + item.title + '"' + (author ? ' author:"' + author + '"' : ""));
      doc = pickDoc(docs, item.title);
      if (!doc) {
        docs = await olSearch(item.title + " " + (item.series || author || ""));
        doc = pickDoc(docs, item.title);
      }
    }

    if (needFetch && doc) {
      const d = detailsFromDoc(doc);
      const synopsis = await workDescription(doc.key);
      if (synopsis) d.synopsis = synopsis;
      if (Object.keys(d).length) {
        d.source = "openlibrary";
        details[item.id] = d;
      }
    }
  } catch (err) {
    console.log(`  ! ${item.id}: ${err.message}`);
  }

  done++;
  if (done % 20 === 0) {
    save();
    console.log(`${done} processed, ${Object.keys(details).length} enriched, ${audit.length} audit flags`);
  }
}

save();
const withSynopsis = Object.values(details).filter((d) => d.synopsis).length;
console.log(`DONE: ${Object.keys(details).length}/${queue.length} enriched (${withSynopsis} with synopsis), ${audit.length} audit flags -> ${AUDIT_FILE}`);
